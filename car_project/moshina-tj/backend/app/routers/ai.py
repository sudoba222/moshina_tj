import logging
from typing import Literal, Optional

import anthropic
import groq
from fastapi import APIRouter, Depends, HTTPException, Request, status
from pydantic import BaseModel, field_validator

from app.auth import get_current_user
from app.config import settings
from app.limiter import limiter
from app.models import User
from app.schemas import ApiResponse

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/ai", tags=["ai"])


# ---------------------------------------------------------------------------
# Request schema
# ---------------------------------------------------------------------------

class RefineDescriptionRequest(BaseModel):
    brand: str
    model: str
    year: int
    price: Optional[float] = None
    currency: Literal["USD", "TJS"]
    mileage: Optional[int] = None
    fuel: Optional[str] = None
    transmission: Optional[str] = None
    color: Optional[str] = None
    city: str
    type: Literal["sale", "rent"]
    description: Optional[str] = None   # existing description to refine
    language: Literal["ru", "tj"] = "ru"

    @field_validator("brand", "model", "city")
    @classmethod
    def short_string(cls, v: str) -> str:
        v = v.strip()
        if len(v) > 100:
            raise ValueError("Field must be at most 100 characters")
        return v

    @field_validator("fuel", "transmission", "color")
    @classmethod
    def optional_short_string(cls, v: Optional[str]) -> Optional[str]:
        if v is not None and len(v) > 100:
            raise ValueError("Field must be at most 100 characters")
        return v

    @field_validator("description")
    @classmethod
    def description_max(cls, v: Optional[str]) -> Optional[str]:
        if v is not None and len(v) > 2000:
            raise ValueError("Description must be at most 2000 characters")
        return v


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

_SYSTEM_PROMPT = (
    "You are an expert car listing copywriter for a Tajikistan car marketplace. "
    "Write professional, honest, and appealing car listing descriptions. "
    "Be concise (2-4 sentences max). No emoji."
)


def _build_user_message(req: RefineDescriptionRequest) -> str:
    parts: list[str] = []

    parts.append(
        f"Write a professional car listing description for: "
        f"{req.year} {req.brand} {req.model}"
    )

    if req.fuel:
        parts.append(f"{req.fuel}")
    if req.transmission:
        parts.append(f"{req.transmission}")
    if req.mileage is not None:
        parts.append(f"{req.mileage}km")
    if req.color:
        parts.append(f"{req.color}")

    # Reconstruct the sentence with all collected details
    detail_str = ", ".join(parts[1:])  # everything after the intro phrase
    intro = parts[0]
    full_intro = f"{intro}, {detail_str}" if detail_str else intro

    language_label = "Russian" if req.language == "ru" else "Tajik"

    price_str = f"price {req.price} {req.currency}, " if req.price is not None else ""

    message = (
        f"{full_intro}, located in {req.city}, "
        f"{price_str}type: {req.type}. "
        f"Existing description to improve: '{req.description or ''}'. "
        f"Language: {language_label}."
    )
    return message


# ---------------------------------------------------------------------------
# Endpoint
# ---------------------------------------------------------------------------

@router.post(
    "/refine-description",
    response_model=ApiResponse[str],
    summary="AI-powered car listing description refinement",
)
@limiter.limit("5/minute")
def refine_description(
    request: Request,
    body: RefineDescriptionRequest,
    current_user: User = Depends(get_current_user),
) -> ApiResponse[str]:
    """
    Takes car listing details and returns a refined, professionally written
    description generated by AI (Groq or Anthropic).

    - Requires authentication (prevents API quota abuse).
    - Rate limited to 5 requests per minute per IP.
    - Returns 503 if no AI service is configured or the call fails.
    """
    user_message = _build_user_message(body)

    # 1. Try Groq (Preferred free/low cost)
    if settings.groq_api_key:
        try:
            client = groq.Groq(api_key=settings.groq_api_key)
            completion = client.chat.completions.create(
                model="llama-3.3-70b-versatile",
                messages=[
                    {"role": "system", "content": _SYSTEM_PROMPT},
                    {"role": "user", "content": user_message},
                ],
                max_tokens=512,
                temperature=0.7,
            )
            refined_text = completion.choices[0].message.content.strip()
            return ApiResponse(success=True, data=refined_text, message="Description refined via Groq")
        except Exception as e:
            # If Anthropic is not configured, we'll error out here, otherwise we try Anthropic
            if not settings.anthropic_api_key:
                logger.error("AI error (Groq): %s", e)
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail="AI service temporarily unavailable",
                )

    # 2. Try Anthropic (Fallback)
    if settings.anthropic_api_key:
        try:
            client = anthropic.Anthropic(api_key=settings.anthropic_api_key)
            response = client.messages.create(
                model="claude-3-haiku-20240307",
                max_tokens=512,
                system=_SYSTEM_PROMPT,
                messages=[{"role": "user", "content": user_message}],
            )
            refined_text = response.content[0].text.strip()
            return ApiResponse(success=True, data=refined_text, message="Description refined via Anthropic")
        except Exception as e:
            logger.error("AI error (Anthropic): %s", e)
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="AI service temporarily unavailable",
            )

    # 3. Neither configured
    raise HTTPException(
        status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
        detail="AI service not configured: GROQ_API_KEY or ANTHROPIC_API_KEY is missing",
    )
