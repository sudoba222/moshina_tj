export type StringsShape = typeof strings

export function t(key: string, lang: Lang): string {
  const parts = key.split('.')
  let node: Record<string, unknown> | undefined = strings as Record<string, unknown>
  for (const part of parts) {
    node = node?.[part] as Record<string, unknown> | undefined
  }
  return (node as Record<Lang, string>)?.[lang] ?? key
}

